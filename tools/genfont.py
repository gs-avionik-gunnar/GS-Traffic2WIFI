#!/usr/bin/env python3
"""Generates GS-Traffic2WIFI/DialFont.cpp (anti-aliased 2 bpp bitmap fonts, ASCII 32..126; the large font only has the characters in LARGE_SET)
from DejaVu Sans Bold. Only needed when the font sizes change; the result is committed."""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZES = [("Small", 17, None), ("Medium", 25, None), ("Large", 44, " +-.:%0123456789")]
FIRST, LAST = 32, 126

out = ['// Generated by tools/genfont.py (DejaVu Sans Bold, 2 bpp). Do not edit.',
       '#include "DialFont.h"', '']
for name, px, charset in SIZES:
    f = ImageFont.truetype(TTF, px)
    asc, desc = f.getmetrics()
    h = asc + desc
    widths, offs, data = [], [], bytearray()
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        if charset is not None and ch not in charset:
            widths.append(0)
            offs.append(len(data))
            continue
        adv = f.getlength(ch)
        bb = f.getbbox(ch, anchor="la") if ch != " " else (0, 0, 0, 0)
        w = max(int(round(adv)), bb[2], 1)
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=255, anchor="la")
        offs.append(len(data))
        widths.append(w)
        px_ = im.load()
        for y in range(h):
            for x in range(0, w, 4):
                byte = 0
                for k in range(4):
                    v = (px_[x + k, y] >> 6) if x + k < w else 0  # 0..3
                    byte |= v << (6 - 2 * k)
                data.append(byte)
    out.append("static const uint8_t k%sW[] = {%s};" % (name, ",".join(map(str, widths))))
    out.append("static const uint32_t k%sO[] = {%s};" % (name, ",".join(map(str, offs))))
    out.append("static const uint8_t k%sD[] = {" % name)
    for i in range(0, len(data), 32):
        out.append(",".join("0x%02X" % v for v in data[i:i + 32]) + ",")
    out.append("};")
    out.append("const DialFont kFont%s = {%d, %d, %d, k%sW, k%sO, k%sD};\n" % (name, h, asc, FIRST, name, name, name))
open(sys.argv[1], "w").write("\n".join(out))
